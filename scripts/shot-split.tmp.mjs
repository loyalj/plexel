import { open, settle, waitForEngine, finish, frames } from './harness.mjs'
const { page, url } = await open({ viewport: { width: 1280, height: 800 } })
await page.goto(url)
await waitForEngine(page)
await page.keyboard.down('Control'); await page.keyboard.down('Alt'); await page.keyboard.press('KeyN'); await page.keyboard.up('Alt'); await page.keyboard.up('Control')
await page.waitForSelector('[data-dialog="new"] .dialog-foot .primary')
await page.click('[data-dialog="new"] .dialog-foot .primary')
await settle(800)
await page.keyboard.press('KeyU')
const r = await page.$eval('[data-engine-canvas]', (e) => { const b = e.getBoundingClientRect(); return [b.x, b.y, b.width, b.height] })
await page.mouse.move(r[0] + r[2] * 0.3, r[1] + r[3] * 0.3); await page.mouse.down(); await page.mouse.move(r[0] + r[2] * 0.55, r[1] + r[3] * 0.6, { steps: 6 }); await page.mouse.up()
await settle(300)
await page.evaluate(() => { globalThis.plexel.views().toggleSplit() })
await settle(400)
await page.evaluate(() => globalThis.plexel.engine().call('render.idle', {}))
await page.screenshot({ path: process.argv[2] })
console.log(JSON.stringify(await page.evaluate(() => ({ panes: globalThis.plexel.engine().panes(), size: globalThis.plexel.engine().canvasSize(), split: globalThis.plexel.views().isSplit() }))))
await finish()
