// --- sizing the brush on the canvas ----------------------------------------------------------
console.log('\nsizing the brush')
await press('KeyB')
{
  const before = await page.evaluate(() => globalThis.plexel.brushes().get().brush)
  const steps0 = await page.evaluate(() => globalThis.plexel.documents().active().history.past.length)
  const [cx, cy] = await centre()
  await page.mouse.move(cx, cy)
  await page.keyboard.down('Alt')
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(cx + 40, cy - 60, { steps: 6 })
  await frames(page)
  check('Alt and a right-drag show the tip and its numbers', (await visibleSel('[data-brush-hud] .brush-hud-tip')) && /px/.test(await page.$eval('[data-brush-hud]', (e) => e.textContent)))
  check('the status bar says what the drag does', /hardness/.test(await hintsText()), await hintsText())
  await keep('brush-hud')
  await page.mouse.up({ button: 'right' })
  await page.keyboard.up('Alt')
  await frames(page)
  const after = await page.evaluate(() => globalThis.plexel.brushes().get().brush)
  // At 100%, 40 pixels right is 80 more across; 60 up is 30% harder.
  check('right makes it larger, by twice the drag at 100%', Math.abs(after.size - (before.size + 80)) <= 2, `${before.size} → ${after.size}`)
  check('up makes it harder', after.hardness > before.hardness || after.hardness === 1, `${before.hardness} → ${after.hardness}`)
  check('the tip goes when the drag ends, with no context menu after it', !(await page.$('[data-brush-hud]')) && !(await page.$('[data-context-menu]')))
  const steps1 = await page.evaluate(() => globalThis.plexel.documents().active().history.past.length)
  check('and nothing was painted', steps1 === steps0, `${steps0} → ${steps1} steps, the last ${await page.evaluate(() => globalThis.plexel.documents().active().history.label)}`)
}

